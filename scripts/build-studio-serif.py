"""Rebuild the designer studio's offline title face (fontTools + brotli).

Inputs and their licenses are recorded in the approved design's font-source/.
The subset covers the 2500 most frequent level-1 standard characters plus every
CJK character used by the packaged assistant text, ASCII and punctuation; other
characters retain the platform's serif fallback. No customer text is used to
subset the font. The Brotli font, Less stub and OFL are packaged; the base64
JavaScript copy is retained locally and excluded from uploads. Hinting and glyph
names are dropped (neither affects outline rendering) to stay inside the 2MB
WeChat subpackage budget: the full 3500-character coverage measured 679.9KB and
pushed the compiled assistant preview over the limit.
"""
import base64
import brotli
import io
import re
import json
from pathlib import Path

from fontTools import subset
from fontTools.ttLib import TTFont

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "design-references/designer-portfolio-publishing-v1/redesign-proposal/font-source"
ASSISTANT = ROOT / "miniprogram/packages/assistant"
FREQUENCY_ORDER = re.findall(r"[\u4e00-\u9fff]", (SOURCE / "common-level-1.txt").read_text(encoding="utf-8"))
assert len(FREQUENCY_ORDER) == 3500
SUBSET_SIZE = 2500
characters = set(FREQUENCY_ORDER[:SUBSET_SIZE])
for source in ASSISTANT.rglob("*"):
    if source.suffix in {".wxml", ".js", ".less", ".json"} and source.name != "studio-serif-data.js":
        characters.update(re.findall(r"[\u4e00-\u9fff]", source.read_text(encoding="utf-8", errors="ignore")))
characters.update(chr(code) for code in range(32, 127))
characters.update("，。㎡·《》：；、！（）—")
font = TTFont(SOURCE / "NotoSerifSC-Black.otf")
options = subset.Options()
options.desubroutinize = True
options.hinting = False
options.glyph_names = False
options.layout_features = []
options.recalc_timestamp = False
options.name_IDs = [0, 1, 2, 3, 4, 5, 6, 13, 14]
subsetter = subset.Subsetter(options=options)
subsetter.populate(text="".join(sorted(characters)))
subsetter.subset(font)
font.flavor = "woff2"
buffer = io.BytesIO()
font.save(buffer)
encoded = base64.b64encode(buffer.getvalue()).decode("ascii")
stylesheet = "/* Noto Serif SC Black / SIL OFL. Shared offline payload loaded by lib/studio-font.js; rebuild: scripts/build-studio-serif.py. */\n"
target = ROOT / "miniprogram/packages/assistant/designer/studio-serif.less"
target.write_text(stylesheet, encoding="utf-8")
data_target = ROOT / "miniprogram/packages/assistant/assets/studio-serif-data.js"
data_target.write_text("/* Noto Serif SC Black, SIL OFL 1.1. Generated by scripts/build-studio-serif.py. */\nmodule.exports = " + json.dumps("data:font/woff2;base64," + encoded) + ";\n", encoding="utf-8")
binary_target = data_target.with_name("studio-serif.woff2.br")
binary_target.write_bytes(brotli.compress(buffer.getvalue(), quality=11))
print(f"{len(characters)} codepoints (top {SUBSET_SIZE} + UI text); {len(buffer.getvalue())} shared font bytes; {len(binary_target.read_bytes())} Brotli bytes")
