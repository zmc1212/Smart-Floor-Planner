import { fail } from '@/lib/assistant/contracts';
import type { SynthesisContext, SynthesisSource } from '@/lib/assistant/agent/synthesis';
import type { ReportSourceScope } from '@/lib/assistant/agent/report-source-scope';
import { reportSectionKinds, type ReportBody, type ReportSectionKind } from './report-composition';
import type { FollowupAudience, ReportProject } from './report-scope';

/** The three sections the server writes itself when enterprise knowledge is
 * unavailable (or when only a guidance line is model-written). A server-derived
 * citation is attached only to these exact sentences: a model-written claim is
 * never retroactively labelled as supported by a record it did not cite. */
export const serverSectionText = {
  progress: '进展以本份报告的原记录为准。',
  pending: '待核对项以本份报告的原记录为准。',
  arrangements: '安排以本份报告中已确认的原记录为准。',
} as const;

export const noVerifiedCitationText = '（本段没有可核验的原记录引用）';
export const rejectedCitationText = '（本段引用的来源未通过当前校验，已隐藏）';

type ReportCitation = { sourceId: string; quote: string };
export type ReportCitationProject = {
  projectId: string;
  selection: ReportBody['projects'][number]['selection'];
  context: SynthesisContext;
  facts: ReportProject;
};
export type ReportCitationOriginal = {
  kind: ReportSourceScope['kind'] | 'record' | 'published_pending' | 'issue' | 'arrangement';
  id: string;
  version: number;
  hash?: string;
};

type FactQuote = { quote: string; kind: ReportCitationOriginal['kind']; id: string; version: number; hash?: string };
const languageText = (value: unknown) => typeof value === 'string' ? value.trim() : '';
const minQuote = 4;
const maxQuote = 400;

/** Exact spans of the saved originals, in the same form the report fact text
 * uses. The quote itself is never generated by a model. */
function factQuotes(project: ReportProject, section: ReportSectionKind): FactQuote[] {
  const quotes: FactQuote[] = [];
  const push = (quote: string, item: Omit<FactQuote, 'quote'>) => {
    if (quote.length >= minQuote && quote.length <= maxQuote) quotes.push({ quote, ...item });
  };
  const record = (row: ReportProject['records'][number], quote: string) => push(quote,
    { kind: 'record', id: row.id, version: row.version, hash: row.hash });
  if (section === 'progress') {
    for (const row of project.records) {
      const completed = languageText(row.data.completed);
      if (completed) record(row, '本次完成：' + completed);
    }
  }
  if (section === 'pending') {
    for (const row of project.records) {
      const pending = languageText(row.data.pending), coordination = languageText(row.data.coordination);
      if (pending) record(row, '尚未完成：' + pending);
      if (coordination) record(row, '待沟通：' + coordination);
    }
    const known = new Set(project.records.map(row => row.id));
    for (const item of project.publishedRecordItems || []) {
      // A record already present above keeps its canonical fact lines; the
      // published item only adds a record that fell outside the period window.
      if (known.has(item.recordId)) continue;
      const pending = languageText(item.pending), coordination = languageText(item.coordination);
      if (pending) push(pending, { kind: 'published_pending', id: item.recordId, version: item.recordVersion, hash: item.sourceHash });
      if (coordination) push(coordination, { kind: 'published_pending', id: item.recordId, version: item.recordVersion, hash: item.sourceHash });
    }
  }
  if (section === 'arrangements') {
    for (const arrangement of project.arrangements || []) {
      const title = languageText(arrangement.title);
      if (!title) continue;
      // The aggregate fact text keeps the title on the header line; a scoped
      // arrangement source places it on the next line. Both spans are real.
      push(`安排${arrangement.id}（版本${arrangement.revision}）：${title}`,
        { kind: 'arrangement', id: arrangement.id, version: arrangement.revision, hash: arrangement.hash });
      push(`安排${arrangement.id}（版本${arrangement.revision}）：`,
        { kind: 'arrangement', id: arrangement.id, version: arrangement.revision, hash: arrangement.hash });
    }
  }
  return quotes;
}

/** Resolve a save-time citation against the exact source text and the current
 * facts. The returned original is the only record identity a view may expose. */
export function verifyReportCitation(project: ReportCitationProject, citation: ReportCitation): ReportCitationOriginal | null | undefined {
  if (!citation || typeof citation.sourceId !== 'string' || typeof citation.quote !== 'string'
    || citation.quote.trim().length < minQuote || citation.quote.length > maxQuote) return undefined;
  const source = project.context.sources.find(candidate => candidate.sourceId === citation.sourceId);
  if (!source || !source.text.includes(citation.quote)) return undefined;
  if (source.kind === 'knowledge') return source.evidence ? null : undefined;
  if (source.kind !== 'project') return undefined;
  const scope = source.reportScope;
  if (scope) {
    if (String(scope.reportId) !== String(project.selection.reportId) || Number(scope.revision) !== Number(project.selection.revision)
      || String(scope.projectId) !== project.projectId || String(scope.factsHash) !== String(project.selection.factsHash)) return undefined;
    if (scope.kind === 'metadata') return null;
    if (scope.kind === 'stage') {
      if (!scope.itemId) return null;
      const event = project.facts.stageEvents.find(candidate => candidate.id === scope.itemId && candidate.revision === scope.itemVersion);
      return event ? { kind: 'stage', id: event.id, version: event.revision } : undefined;
    }
    if (scope.kind === 'record') {
      const row = project.facts.records.find(candidate => candidate.id === scope.itemId && candidate.version === scope.itemVersion
        && (!scope.sourceHash || candidate.hash === scope.sourceHash));
      return row ? { kind: 'record', id: row.id, version: row.version, hash: row.hash } : undefined;
    }
    if (scope.kind === 'published_pending') {
      const item = (project.facts.publishedRecordItems || []).find(candidate => candidate.recordId === scope.itemId
        && candidate.recordVersion === scope.itemVersion && (!scope.sourceHash || candidate.sourceHash === scope.sourceHash));
      return item ? { kind: 'published_pending', id: item.recordId, version: item.recordVersion, hash: item.sourceHash } : undefined;
    }
    if (scope.kind === 'issue') {
      const issue = (project.facts.issues || []).find(candidate => candidate.id === scope.itemId && candidate.revision === scope.itemVersion
        && (!scope.sourceHash || candidate.hash === scope.sourceHash));
      return issue ? { kind: 'issue', id: issue.id, version: issue.revision, hash: issue.hash } : undefined;
    }
    const arrangement = (project.facts.arrangements || []).find(candidate => candidate.id === scope.itemId
      && candidate.revision === scope.itemVersion && (!scope.sourceHash || candidate.hash === scope.sourceHash));
    return arrangement ? { kind: 'arrangement', id: arrangement.id, version: arrangement.revision, hash: arrangement.hash } : undefined;
  }
  // Older saved bodies used one aggregate source. A record header is a real
  // record ID claim and must still exist in the current facts; every other
  // quote is accepted only when it is an exact span of this saved source.
  const header = /原记录\s*(\d+)（版本\s*(\d+)/u.exec(citation.quote);
  if (header) {
    const row = project.facts.records.find(candidate => candidate.id === header[1] && candidate.version === Number(header[2]));
    return row ? { kind: 'record', id: row.id, version: row.version, hash: row.hash } : undefined;
  }
  for (const section of ['progress', 'pending', 'arrangements'] as const) {
    const match = factQuotes(project.facts, section).find(item => item.quote === citation.quote);
    if (match) return { kind: match.kind, id: match.id, version: match.version, hash: match.hash };
  }
  // A field line or record header copied from an older source still names an
  // original. If that exact item is no longer in the revalidated facts, the
  // citation is revoked even though the old source text is still stored.
  if (/^(?:本次完成|尚未完成|待沟通)：/u.test(citation.quote) || /原记录\s*\d+/u.test(citation.quote)) return undefined;
  return null;
}

function sourceFor(sources: SynthesisSource[], item: FactQuote) {
  return sources.find(source => source.kind === 'project' && item.kind !== 'published_pending'
    && source.reportScope?.itemId === item.id && source.reportScope.itemVersion === item.version && source.text.includes(item.quote))
    || sources.find(source => source.kind === 'project' && source.text.includes(item.quote));
}

/** Fill only the server-written sentences whose citations are still empty.
 * Every attached quote exists in the saved fact text and is re-verified through
 * the same resolver used for model citations. */
export function attachReportProjectCitations(bodyProject: ReportBody['projects'][number], project: ReportCitationProject) {
  for (const section of ['progress', 'pending', 'arrangements'] as const) {
    const fixed = serverSectionText[section];
    for (const segment of bodyProject.sections[section].segments) {
      if (segment.citations.length || segment.basis === 'evidence' || segment.text !== fixed) continue;
      const seen = new Set<string>();
      segment.citations = factQuotes(project.facts, section).flatMap(item => {
        const source = sourceFor(project.context.sources, item);
        if (!source || seen.has(item.quote)) return [];
        seen.add(item.quote);
        const citation = { sourceId: source.sourceId, quote: item.quote };
        return verifyReportCitation(project, citation) === undefined ? [] : [citation];
      }).slice(0, 4);
    }
  }
}

export function attachReportFactCitations(body: ReportBody, projects: ReportCitationProject[]) {
  for (const bodyProject of body.projects) {
    const project = projects.find(candidate => candidate.projectId === bodyProject.projectId);
    if (project) attachReportProjectCitations(bodyProject, project);
  }
}

/** Save-time gate: a citation that cannot be resolved to the current facts
 * rejects the whole body instead of silently becoming report prose. Customer
 * recipient facts already exclude records not published to that customer, so
 * the same check refuses an internal record reference. */
export function assertReportBodyCitations(body: ReportBody, projects: ReportCitationProject[], audience?: FollowupAudience) {
  for (const bodyProject of body.projects) {
    const project = projects.find(candidate => candidate.projectId === bodyProject.projectId);
    if (!project) fail('invalid_model_citation', 502);
    for (const section of reportSectionKinds) {
      for (const segment of bodyProject.sections[section].segments) {
        for (const citation of segment.citations) {
          if (verifyReportCitation(project, citation) === undefined) fail('invalid_model_citation', 502);
        }
      }
    }
    if (audience === 'customer' && bodyProject.projectId !== project!.projectId) fail('invalid_model_citation', 502);
  }
}
