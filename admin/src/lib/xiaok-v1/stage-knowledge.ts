export const stageKnowledgeRegistry = (() => {
  const packs = new Map<StageId, StageKnowledgePack>();
  for (const value of stageKnowledgePacks) {
    const pack = stageKnowledgePackSchema.parse(value);
    if (packs.has(pack.stageId) && pack.status === 'active') throw new Error('duplicate_active_stage_knowledge_pack');
    if (!packs.has(pack.stageId) || pack.status === 'active') packs.set(pack.stageId, pack);
  }
  if (stageDefinitions.some(stage => !packs.has(stage.stageId))) throw new Error('missing_stage_knowledge_pack');
  return {
    get: (stageId: StageId) => packs.get(stageId),
    list: () => [...packs.values()],
  };
})();
